// ============================================================================
// rlm-app.js — управление самим приложением RLM (перезапуск) с любого устройства.
//
// Зачем: кнопка «Перезапуск» на ПК зовёт Electron напрямую через мост window.rlm
// (app.relaunch). С телефона/из браузера этого моста нет — поэтому телефон просит
// СЕРВЕР перезапустить приложение. Сервер поднят главным процессом Electron с
// IPC-каналом (stdio 'ipc' в app/main.js), значит может послать ему сигнал 'relaunch',
// а тот делает ТОТ ЖЕ app.relaunch(), что и кнопка на ПК. Сервер поднимется заново —
// телефон переподключится сам (клиент ждёт сервер и перезагружает страницу).
//
// Безопасность: маршрут смонтирован ПОСЛЕ whitelist-middleware (см. server-main.js),
// поэтому перезапустить может только уже доверенное устройство (ПК разрешён всегда;
// телефон — после добавления в «Доступ по сети»).
//
// Маршрут (монтируется в server-main.js под /api/rlm/app):
//   POST /restart -> { ok:true }            (затем через ~350мс сигнал Electron на relaunch)
//                 -> { ok:false, unavailable:true, error } если сервер запущен НЕ приложением RLM
// ============================================================================
import express from 'express';

export const router = express.Router();

router.post('/restart', (req, res) => {
    // process.send есть только когда процесс запущен с IPC-каналом — т.е. поднят Electron'ом
    // (app/main.js). Запущен вручную в терминале (dev) → перезапускать некому, честно скажем.
    // Флаг unavailable отличает этот отказ от простого обрыва связи на стороне клиента.

    // Termux: Electron'а там нет вообще — сервер запущен из start-termux.sh, который крутит его
    // в цикле. Значит перезапуск = выйти с кодом 42, скрипт поднимет заново уже с новым кодом.
    if (typeof process.send !== 'function' && process.env.RLM_RELOOP === '1') {
        res.json({ ok: true });
        setTimeout(() => process.exit(42), 350);
        return;
    }
    if (typeof process.send !== 'function') {
        return res.json({ ok: false, unavailable: true, error: 'Перезапуск доступен только когда сервер запущен приложением RLM.' });
    }
    // Сначала отвечаем телефону (пусть покажет «переподключаюсь»), ПОТОМ уводим приложение в relaunch —
    // иначе ответ не успеет уйти до обрыва связи.
    res.json({ ok: true });
    setTimeout(() => {
        try { process.send({ rlm: 'relaunch' }); } catch (e) { console.error('rlm-app restart signal:', e); }
    }, 350);
});
